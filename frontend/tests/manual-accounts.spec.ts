 expect(replacement.available_quantity).toBe('23.000000')
 expect(replacement.unit_cost_mmk).toBe('120.00000000')
 expect(replacement.carton_size).toBe(oldStock.carton_size)
 expect(correctedStock.find((r:{batch_id:string})=>r.batch_id===oldStock.batch_id).available_quantity).toBe('0.000000')
 const afterCorrection=await get(`/sales/${sale.id}`)
 expect(afterCorrection.cost_mmk).toBe(historicInvoice.cost_mmk)
 expect(afterCorrection.profit_mmk).toBe(historicInvoice.profit_mmk)
 const futureQuote=await post('/pos/quote',{request_id:crypto.randomUUID(),account_id:account.id,warehouse_id:warehouse.id,pricing_mode:'RETAIL',payment_method:'BANK_TRANSFER',tender_mmk:'150',sell_on_credit:false,items:[{product_id:product.id,unit_code:'PIECE',units_per_pack:'1',quantity:'1',unit_price_mmk:'150',discount_mmk:'0'}]},200)
 expect(futureQuote.lines[0].cost_mmk).toBe('120.0000')
 await page.getByRole('row').filter({hasText:replacement.batch_number}).getByRole('button',{name:'Correct landed cost',exact:true}).click()
