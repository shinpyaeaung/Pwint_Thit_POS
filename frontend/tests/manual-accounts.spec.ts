import {test,expect} from '@playwright/test'
import {signIn} from './session'
test('manual stock and accounts: stock, sale, refund, bank balance and personal separation',async({page})=>{
 test.setTimeout(120000)
 await signIn(page,'browser-packaging-owner')
 const suffix=crypto.randomUUID().slice(0,8),headers={Origin:process.env.E2E_BASE_URL!,'X-Pwint-Thit-Request':'1'}
 const post=async(path:string,data:unknown,status=201)=>{const r=await page.request.post(`/api/v1${path}`,{headers,data});expect(r.status(),await r.text()).toBe(status);return r.json()}
 const get=async(path:string)=>{const r=await page.request.get(`/api/v1${path}`);expect(r.status(),await r.text()).toBe(200);return r.json()}
 const choose=async(label:string,name:string)=>{await page.getByRole('combobox',{name:label,exact:true}).click();await page.getByRole('option',{name,exact:true}).click()}
 const product=await post('/products',{name:`Opening ${suffix}`,base_unit_code:'PIECE',is_active:true,packaging:[{unit_code:'PIECE',units_per_pack:'1',is_default_purchase:true,is_default_sale:true},{unit_code:'CARTON',units_per_pack:'12'}]})
 const warehouse=await post('/warehouses',{name:`Opening ${suffix}`,code:`OP-${suffix}`})
 await page.goto('/inventory');await page.getByRole('button',{name:'Add existing stock',exact:true}).click()
 await choose('Manual stock warehouse',`Opening ${suffix}`)
 await page.getByLabel('Find stock product',{exact:true}).fill(suffix)
 await page.getByRole('combobox',{name:'Manual stock product',exact:true}).click();await page.getByRole('option').filter({hasText:`Opening ${suffix}`}).click()
 await choose('Manual stock unit','CARTON · 12 PIECE')
 await page.getByLabel('Stock quantity',{exact:true}).fill('2')
 await page.getByLabel('Actual cost per PIECE (MMK)',{exact:true}).fill('100')
 await page.getByLabel('Retail price per PIECE (MMK)',{exact:true}).fill('150')
 await page.getByLabel('Wholesale price per PIECE (MMK)',{exact:true}).fill('140')
 await page.getByLabel('Stock entry reason',{exact:true}).fill('Verified opening count')
 await page.getByRole('button',{name:'Post existing stock',exact:true}).click();await expect(page.getByRole('dialog')).toHaveCount(0)
 await page.getByRole('searchbox').fill(suffix)
 await expect(page.getByRole('table')).toContainText('24')
 await page.goto('/accounts');await page.getByRole('button',{name:'Add account',exact:true}).click()
 await page.getByLabel('Bank Name',{exact:true}).fill(`KBZ ${suffix}`);await page.getByLabel('Account Holder Name',{exact:true}).fill(`Owner ${suffix}`);await page.getByLabel('Account Number',{exact:true}).fill('123456')
 await page.getByRole('button',{name:'Save account',exact:true}).click();await expect(page.getByRole('dialog')).toHaveCount(0)
 const account=(await get('/accounts')).accounts.find((a:{bank:string})=>a.bank===`KBZ ${suffix}`)
 await page.getByRole('button',{name:'Record transaction',exact:true}).click();await choose('Entry account',account.name)
 await page.getByLabel('Transaction amount (MMK)',{exact:true}).fill('1000')
 await page.getByLabel('Deposit sender',{exact:true}).fill('Family deposit')
 const transactionDate=new Date(Date.now()-86400000+390*60000).toISOString().slice(0,10)
 await page.getByLabel('Transaction date (Myanmar)',{exact:true}).fill(transactionDate)
 await expect(page.getByLabel('Transaction time (Myanmar)',{exact:true})).toHaveCount(0)
 await expect(page.getByLabel('Transaction date (Myanmar)',{exact:true})).toHaveValue(transactionDate)

 await page.getByLabel('Description / reason',{exact:true}).fill(`External ${suffix}`)
 await page.getByRole('button',{name:'Post account entry',exact:true}).click();await expect(page.getByRole('dialog')).toHaveCount(0)
 await choose('History account',account.name)
 await expect(page.getByRole('table')).toContainText('Family deposit')
 const recorded=(await get(`/accounts/history?account_id=${account.id}`)).entries.find((e:{description:string})=>e.description===`External ${suffix}`)
 expect(new Date(new Date(recorded.occurred_at).getTime()+390*60000).toISOString().slice(0,10)).toBe(transactionDate)
 // Simulate a committed sale whose success body is lost on the way back.
 // Retrying must preserve the request and produce exactly one cash/stock effect.
 await page.goto('/pos')
 await choose('POS warehouse',`Opening ${suffix}`)
 await page.getByLabel('Scan barcode or search products',{exact:true}).fill(suffix)
 const posProduct=(await get(`/pos/products?warehouse_id=${warehouse.id}&q=${suffix}`))[0]
 await page.getByRole('button',{name:`Add ${posProduct.sku}`,exact:true}).click()
 await page.getByLabel(`Quantity ${posProduct.sku}`,{exact:true}).fill('2')
 await choose('Payment method','Bank transfer')
 await choose('Bank / cash account',`${account.name} · ${account.bank}`)
 await page.getByRole('button',{name:'Review checkout · F8',exact:true}).click()
 let postedID='', firstPayload=''
 await page.route('**/api/v1/pos/checkout',async route=>{
  const payload=route.request().postData()!
  if(firstPayload) expect(payload).toBe(firstPayload)
  else firstPayload=payload
  const response=await route.fetch()
  expect(response.status(),await response.text()).toBe(201)
  const result=await response.json()
  if(!postedID){postedID=result.id;await route.fulfill({response,body:'{"id":'})}
  else {expect(result.id).toBe(postedID);await route.fulfill({response})}
 })
 const review=page.getByRole('dialog',{name:'Review checkout',exact:true})
 await review.getByRole('button',{name:'Complete sale',exact:true}).click()
 await expect(review.getByRole('alert')).toContainText('Retry this same checkout')
 await expect(review.getByRole('button',{name:'Back',exact:true})).toBeDisabled()
 await review.getByRole('button',{name:'Complete sale',exact:true}).click()
 await expect(page).toHaveURL(/\/sales\/[a-f0-9-]+$/)
 await page.unroute('**/api/v1/pos/checkout')
 const sale={id:postedID}
 expect((await get('/accounts')).accounts.find((a:{id:string})=>a.id===account.id).balance_mmk).toBe('1300.0000')
 const stock=(await get(`/inventory?warehouse_id=${warehouse.id}`)).stock
 expect(stock.find((row:{product_id:string})=>row.product_id===product.id).available_quantity).toBe('22.000000')
 const source=await get(`/returns/sales/${sale.id}`)
 const body={account_id:account.id,request_id:crypto.randomUUID(),sale_id:sale.id,purchase_id:'',replacement_sale_id:'',warehouse_id:'',resolution:'REFUND',reason:`Return ${suffix}`,method:'BANK_TRANSFER',reference:'',approve_refund:false,quote_hash:'',items:[{sale_item_batch_id:source.items[0].sale_item_batch_id,quantity:'1',disposition:'SELLABLE',bucket:''}]}
 const preview=await post('/returns/sales/preview',body,200);await post('/returns/sales',{...body,approve_refund:true,quote_hash:preview.quote_hash},200)
 await page.goto('/returns');await expect(page.getByRole('table')).toContainText(`Opening ${suffix} · 1 PIECE`)
 await page.goto('/accounts');await choose('History account',account.name)
 await page.getByRole('button',{name:'Record transaction',exact:true}).click();await choose('Entry type','Personal expense')
 await page.getByLabel('Transaction amount (MMK)',{exact:true}).fill('50');await page.getByLabel('Description / reason',{exact:true}).fill(`Personal ${suffix}`)
 await page.getByRole('button',{name:'Post account entry',exact:true}).click();await expect(page.getByRole('dialog')).toHaveCount(0)
 expect((await get('/accounts')).accounts.find((a:{id:string})=>a.id===account.id).balance_mmk).toBe('1100.0000')
 // Manual reconciliation is an explicit dated difference, not a replacement of history.
 await page.locator('section .panel').filter({has:page.getByText(`Owner ${suffix}`,{exact:true})}).getByRole('button',{name:'Update actual balance',exact:true}).click()
 await expect(page.getByLabel('Transaction date (Myanmar)',{exact:true})).toBeVisible()
 await expect(page.getByLabel('Transaction time (Myanmar)',{exact:true})).toHaveCount(0)
 await page.getByLabel('Actual account balance (MMK)',{exact:true}).fill('1110')
 await page.getByLabel('Description / reason',{exact:true}).fill('Bank observed balance')
 await page.getByRole('button',{name:'Post account entry',exact:true}).click();await expect(page.getByRole('dialog')).toHaveCount(0)
 await page.reload();await expect(page.getByRole('table')).toContainText('Balance adjustment')
 expect((await get('/accounts')).accounts.find((a:{id:string})=>a.id===account.id).balance_mmk).toBe('1110.0000')
 const card=page.locator('section .panel').filter({has:page.getByText(`Owner ${suffix}`,{exact:true})})
 await card.getByRole('button',{name:'Manage account',exact:true}).click()
 await page.getByLabel('Bank Name',{exact:true}).fill('KBZ edited')
 await page.getByLabel('Account Number',{exact:true}).fill('Savings')
 await page.getByRole('button',{name:'Save account',exact:true}).click()
 await expect(page.getByRole('dialog')).toHaveCount(0)
 await page.reload()
 await expect(card).toContainText('KBZ edited')
 await expect(card).toContainText('Savings')
 await card.getByRole('button',{name:'Archive Account',exact:true}).click()
 await expect(card).toContainText('Archived')
 expect((await get('/accounts/options')).some((a:{id:string})=>a.id===account.id)).toBe(false)
 expect((await get('/accounts')).accounts.find((a:{id:string})=>a.id===account.id).balance_mmk).toBe('1110.0000')
 await expect(page.getByRole('table')).toContainText('Bank observed balance')
 await card.getByRole('button',{name:'Restore Account',exact:true}).click()
 await expect(card.getByRole('button',{name:'Archive Account',exact:true})).toBeVisible()
 expect((await get('/accounts/options')).some((a:{id:string})=>a.id===account.id)).toBe(true)
 await page.setViewportSize({width:390,height:844});await expect(page.getByRole('heading',{name:'Accounts & balances',exact:true})).toBeVisible()
 await page.screenshot({path:`/tmp/pwint-accounts-${test.info().project.name}.png`,fullPage:true})
 await card.getByRole('button',{name:'Delete permanently',exact:true}).click()
 const dialog=page.getByRole('dialog')
 await expect(dialog).toContainText('Linked invoices may become unpaid')
 await expect(dialog.getByRole('button',{name:'Delete permanently',exact:true})).toBeDisabled()
 await page.getByLabel(`Type account name: ${account.name}`,{exact:true}).fill(account.name)
 await page.getByLabel('Deletion reason',{exact:true}).fill('Remove disposable browser account and payment history')
 await dialog.getByRole('button',{name:'Delete permanently',exact:true}).click()
 await expect(dialog).toHaveCount(0)
 await expect(card).toHaveCount(0)
 await page.reload()
 expect((await get('/accounts')).accounts.some((a:{id:string})=>a.id===account.id)).toBe(false)
 expect((await get('/accounts/options')).some((a:{id:string})=>a.id===account.id)).toBe(false)
 expect((await get(`/accounts/history?account_id=${account.id}`)).total).toBe(0)
 // The sale and its stock movements remain available after erasing payment history.
 expect((await get(`/returns/sales/${sale.id}`)).items.length).toBeGreaterThan(0)

})
